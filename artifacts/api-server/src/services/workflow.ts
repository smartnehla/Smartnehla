function ensureSafeFiles(job: SolutionJob): Array<{ path: string; content: string }> {
  const files = job.generatedFiles.filter(
    (file) => file.path !== "package.json" && file.path !== "pnpm-lock.yaml",
  );
  if (!files.some((file) => file.path === "app/page.tsx")) {
    throw new Error("Generated project is missing app/page.tsx. Create a new preview.");
  }
  if (!files.some((file) => file.path === "app/layout.tsx")) {
    throw new Error("Generated project is missing app/layout.tsx. Create a new preview.");
  }
  return [
    ...files,
    { path: "package.json", content: repoPackage(job.repoName) },
    {
      path: ".gitignore",
      content: "node_modules\n.next\nout\n.env*\n.vercel\n.DS_Store\n",
    },
  ];
}

async function githubRequest(
  path: string,
  method = "GET",
  data?: unknown,
): Promise<Response> {
  return connectors.proxy(githubConnector, path, {
    method,
    headers: {
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      ...(data === undefined ? {} : { "Content-Type": "application/json" }),
    },
    ...(data === undefined ? {} : { body: JSON.stringify(data) }),
  });
}

async function parseGitHub<T>(response: Response): Promise<T> {
  if (!response.ok) throw new Error(`GitHub request failed (${response.status}).`);
  return (await response.json()) as T;
}

async function createRepositoryAndPush(job: SolutionJob): Promise<string> {
  const meResponse = await githubRequest("/user");
  const me = await parseGitHub<{ login: string }>(meResponse);
  const description = `Generated by Smart Nehla job ${job.id}`;
  const createResponse = await githubRequest("/user/repos", "POST", {
    name: job.repoName,
    description,
    private: true,
    auto_init: true,
  });

  let repo: { owner: { login: string }; name: string; default_branch: string };
  if (createResponse.status === 422) {
    const existingResponse = await githubRequest(
      `/repos/${encodeURIComponent(me.login)}/${encodeURIComponent(job.repoName)}`,
    );
    const existing = await parseGitHub<{
      owner: { login: string };
      name: string;
      default_branch: string;
      description: string | null;
    }>(existingResponse);
    if (existing.description !== description) {
      throw new Error("A repository with this name already exists and was not created by this job.");
    }
    repo = existing;
  } else {
    repo = await parseGitHub(createResponse);
  }

  const owner = encodeURIComponent(repo.owner.login);
  const name = encodeURIComponent(repo.name);
  const branch = encodeURIComponent(repo.default_branch || "main");
  const ref = await parseGitHub<{ object: { sha: string } }>(
    await githubRequest(`/repos/${owner}/${name}/git/ref/heads/${branch}`),
  );
  const parentSha = ref.object.sha;
  const parentCommit = await parseGitHub<{ tree: { sha: string } }>(
    await githubRequest(`/repos/${owner}/${name}/git/commits/${parentSha}`),
  );
  const files = ensureSafeFiles(job);
  const tree = await parseGitHub<{ sha: string }>(
    await githubRequest(`/repos/${owner}/${name}/git/trees`, "POST", {
      base_tree: parentCommit.tree.sha,
      tree: files.map((file) => ({
        path: file.path,
        mode: "100644",
        type: "blob",
        content: file.content,
      })),
    }),
  );
  const commit = await parseGitHub<{ sha: string }>(
    await githubRequest(`/repos/${owner}/${name}/git/commits`, "POST", {
      message: "Create generated micro-app",
      tree: tree.sha,
      parents: [parentSha],
    }),
  );
  await parseGitHub(
    await githubRequest(`/repos/${owner}/${name}/git/refs/heads/${branch}`, "PATCH", {
      sha: commit.sha,
      force: false,
    }),
  );
  return `https://github.com/${repo.owner.login}/${repo.name}`;
}

function quoteIdentifier(value: string): string {
  if (!/^[a-z][a-z0-9_]{0,62}$/.test(value)) {
    throw new Error("Generated database schema contains an invalid identifier.");
  }
  return `"${value}"`;
}

function buildSupabaseSql(job: SolutionJob): string {
  const typeMap = {
    text: "text",
    integer: "integer",
    boolean: "boolean",
    numeric: "numeric",
    timestamptz: "timestamptz",
    uuid: "uuid",
  } as const;
  return job.generatedTables
    .map((table) => {
      const tableName = quoteIdentifier(`sn_${job.repoName.replaceAll("-", "_")}_${table.name}`);
      const columns = table.columns.map((column) => {
        if (column.name === "id" || column.name === "created_at") {
          throw new Error("Generated table columns cannot redefine id or created_at.");
        }
        const nullable = column.nullable ? "" : " not null";
        return `${quoteIdentifier(column.name)} ${typeMap[column.type as keyof typeof typeMap]}${nullable}`;
      });
      return `create table if not exists public.${tableName} ("id" uuid primary key default gen_random_uuid(), "created_at" timestamptz not null default now()${columns.length ? `, ${columns.join(", ")}` : ""});`;
    })
    .join("\n");
}

async function provisionSupabase(job: SolutionJob): Promise<void> {
  if (job.generatedTables.length === 0) return;
  const token = process.env.SUPABASE_ACCESS_TOKEN;
  const projectUrl = process.env.SUPABASE_URL;
  if (!token || !projectUrl) throw new Error("Supabase credentials are not configured.");
  const projectRef = new URL(projectUrl).hostname.split(".")[0];
  if (!projectRef || !/^[a-z0-9]{10,30}$/.test(projectRef)) {
    throw new Error("SUPABASE_URL is not a valid Supabase project URL.");
  }
  const response = await fetch(
    `https://api.supabase.com/v1/projects/${projectRef}/database/query`,
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ query: buildSupabaseSql(job), read_only: false }),
      signal: AbortSignal.timeout(30_000),
    },
  );
  if (!response.ok) {
    throw new Error(
      response.status === 401 || response.status === 403
        ? "Supabase rejected the management token or its database permissions."
        : `Supabase table setup failed (${response.status}).`,
    );
  }
}

async function vercelRequest(path: string, method = "GET", data?: unknown): Promise<Response> {
  const token = process.env.VERCEL_TOKEN;
  if (!token) throw new Error("VERCEL_TOKEN is not configured.");
  return fetch(`https://api.vercel.com${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      ...(data === undefined ? {} : { "Content-Type": "application/json" }),
    },
    ...(data === undefined ? {} : { body: JSON.stringify(data) }),
    signal: AbortSignal.timeout(30_000),
  });
}

async function deployToVercel(job: SolutionJob): Promise<string> {
  const files = ensureSafeFiles(job).map((file) => ({
    file: file.path,
    data: Buffer.from(file.content, "utf8").toString("base64"),
    encoding: "base64",
  }));
  const teamId = process.env.VERCEL_TEAM_ID;
  const params = new URLSearchParams({ forceNew: "1", skipAutoDetectionConfirmation: "1" });
  if (teamId) params.set("teamId", teamId);
  const response = await vercelRequest(`/v13/deployments?${params}`, "POST", {
    name: job.repoName,
    files,
    projectSettings: {
      framework: "nextjs",
      buildCommand: "npm run build",
      installCommand: "npm install",
      outputDirectory: ".next",
    },
    target: "production",
  });
  if (!response.ok) {
    throw new Error(
      response.status === 401 || response.status === 403
        ? "Vercel rejected the token or its deployment permissions."
        : `Vercel did not accept the deployment (${response.status}).`,
    );
  }
  const deployment = (await response.json()) as { id: string; url?: string };
  if (!deployment.id) throw new Error("Vercel returned no deployment ID.");
  const initialUrl = deployment.url ? `https://${deployment.url}` : null;
  await db.update(solutionJobsTable)
    .set({ liveUrl: initialUrl })
    .where(eq(solutionJobsTable.id, job.id));

  const seenEvents = new Set<string>();
  const deadline = Date.now() + 8 * 60_000;
  while (Date.now() < deadline) {
    const statusResponse = await vercelRequest(`/v13/deployments/${encodeURIComponent(deployment.id)}`);
    if (statusResponse.ok) {
      const status = (await statusResponse.json()) as {
        readyState?: string;
        state?: string;
        url?: string;
        errorCode?: string;
      };
      const readyState = status.readyState ?? status.state ?? "";
      if (status.url && status.url !== deployment.url) {
        await db.update(solutionJobsTable)
          .set({ liveUrl: `https://${status.url}` })
          .where(eq(solutionJobsTable.id, job.id));
      }

      const eventsResponse = await vercelRequest(
        `/v3/deployments/${encodeURIComponent(deployment.id)}/events?limit=30`,
      );
      if (eventsResponse.ok) {
        const events = (await eventsResponse.json()) as Array<{
          id?: string;
          type?: string;
          payload?: { text?: string; textDelta?: string };
        }>;
        for (const event of events.slice(-20)) {
          const eventId = event.id ?? `${event.type}:${event.payload?.text ?? event.payload?.textDelta ?? ""}`;
          const message = event.payload?.text ?? event.payload?.textDelta;
          if (message && !seenEvents.has(eventId)) {
            seenEvents.add(eventId);
            await writeJobLog(job.id, "info", message.slice(0, 1000));
          }
        }
      }

      if (readyState === "READY") {
        return `https://${status.url ?? deployment.url}`;
      }
      if (readyState === "ERROR" || readyState === "CANCELED") {
        throw new Error(`Vercel build ended in ${readyState}${status.errorCode ? ` (${status.errorCode})` : ""}.`);
      }
    }
    await new Promise((resolve) => setTimeout(resolve, 5000));
  }
  throw new Error("Vercel deployment did not finish within 8 minutes.");
}

export async function writeJobLog(
  jobId: string,
  level: "info" | "success" | "warning" | "error",
  message: string,
): Promise<void> {
  await db.insert(solutionJobLogsTable).values({ jobId, level, message: message.slice(0, 2000) });
}

async function runJob(job: SolutionJob): Promise<void> {
  try {
    await db.update(solutionJobsTable)
      .set({ status: "running", progress: 5, error: null })
      .where(eq(solutionJobsTable.id, job.id));
    await writeJobLog(job.id, "info", "Checking provider authorization.");
    await writeJobLog(job.id, "info", "Creating the private GitHub repository.");
    const repositoryUrl = await createRepositoryAndPush(job);
    await writeJobLog(job.id, "success", `Generated source pushed to ${repositoryUrl}.`);
    await db.update(solutionJobsTable)
      .set({ progress: 45 })
      .where(eq(solutionJobsTable.id, job.id));

    if (job.generatedTables.length > 0) {
      await writeJobLog(job.id, "info", "Creating approved Supabase tables.");
      await provisionSupabase(job);
      await writeJobLog(job.id, "success", `${job.generatedTables.length} Supabase table(s) created.`);
    } else {
      await writeJobLog(job.id, "info", "No persistent tables were requested; skipping Supabase schema setup.");
    }
    await db.update(solutionJobsTable)
      .set({ progress: 60 })
      .where(eq(solutionJobsTable.id, job.id));

    await writeJobLog(job.id, "info", "Submitting the reviewed project to Vercel.");
    const liveUrl = await deployToVercel(job);
    await db.update(solutionJobsTable)
      .set({ status: "succeeded", progress: 100, liveUrl: liveUrl, error: null })
      .where(eq(solutionJobsTable.id, job.id));
    await writeJobLog(job.id, "success", `Deployment is live at ${liveUrl}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : "The workflow failed unexpectedly.";
    await db.update(solutionJobsTable)
      .set({ status: "failed", error: message, progress: 0 })
      .where(eq(solutionJobsTable.id, job.id));
    await writeJobLog(job.id, "error", message);
    logger.error({ jobId: job.id, err: error }, "Solution-engine workflow failed");
  }
}

let workerActive = false;

export async function processQueuedJobs(): Promise<void> {
  if (workerActive) return;
  workerActive = true;
  try {
    while (true) {
      const [job] = await db.select()
        .from(solutionJobsTable)
        .where(eq(solutionJobsTable.status, "queued"))
        .orderBy(asc(solutionJobsTable.createdAt))
        .limit(1);
      if (!job) break;
      await runJob(job);
    }
  } catch (error) {
    logger.error({ err: error }, "Solution-engine queue worker failed");
  } finally {
    workerActive = false;
  }
}

export function startSolutionJobWorker(): void {
  const interval = setInterval(() => {
    void processQueuedJobs();
  }, 3000);
  interval.unref();
  void db.update(solutionJobsTable)
    .set({ status: "queued", progress: 0 })
    .where(and(eq(solutionJobsTable.status, "running")))
    .then(() => processQueuedJobs())
    .catch((error: unknown) => {
      logger.error({ err: error }, "Could not recover queued solution-engine jobs");
    });
}
